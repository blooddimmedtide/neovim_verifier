"""Write PROGRESS.md: every function in typval.c and typval_encode.c.h with its state.
Usage: python3 -I progress.py <neovim tree> > PROGRESS.md"""
import re, sys
tree = sys.argv[1]
PROVED = {}  # name -> evidence
for line in open(__file__.replace("progress.py", "proved.tsv")):
    if line.strip() and not line.startswith("#"):
        n, ev = line.rstrip("\n").split("\t", 1)
        PROVED[n] = ev
def funcs(path):
    out = []
    for l in open(f"{tree}/{path}").read().split("\n"):
        m = re.match(r"^[A-Za-z_][\w \*]*?\b(\w+)\(", l)
        if m and not l.rstrip().endswith(";") and not l.startswith(("return", "if", "typedef", "#")):
            if m.group(1) not in out:
                out.append(m.group(1))
    return out
print("# typval progress (upstream 7b87ce8)\n")
print("Generated by `python3 -I progress.py <tree>` from `proved.tsv`. A function counts as proved only")
print("when every WP goal of its run is proved (see CLAIM.md for the properties).\n")
tot = done = 0
for path in ["src/nvim/eval/typval.c", "src/nvim/eval/typval_encode.c.h", "src/nvim/eval/typval.h"]:
    fs = funcs(path)
    if path.endswith("typval.h"):
        fs = [f for f in fs if f in PROVED]  # header inlines: only those proved as helpers
    p = [f for f in fs if f in PROVED]; u = [f for f in fs if f not in PROVED]
    if not path.endswith("typval.h"):
        tot += len(fs); done += len(p)
    print(f"## {path}: {len(p)} / {len(fs)} proved\n")
    for f in p:
        print(f"- [x] `{f}`: {PROVED[f]}")
    if u:
        print(f"\n**Still unverified ({len(u)}):** " + ", ".join(f"`{f}`" for f in u))
    print()
print(f"**Total (typval.c + typval_encode.c.h): {done} / {tot} functions proved. The files are not finished.**")
