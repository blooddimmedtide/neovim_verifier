#!/usr/bin/env python3
"""Usage: build.py <neovim checkout> <out.c>
Copies the five leaf functions of src/nvim/linematch.c verbatim (file pinned by sha256)."""
import hashlib, re, sys
PINS = {"7e70347a5f9f63c26366041702ff000ea10ff787ea1ea01e0563535c21f3f492": "upstream 7b87ce8",
        "f11b98b191adda40c5f6501aa1b0b72f95c4960c0f80bb6b94862cc83820affe": "verified_neovim e5db114 (fix)"}
src = open(sys.argv[1] + "/src/nvim/linematch.c", "rb").read()
if hashlib.sha256(src).hexdigest() not in PINS:
    sys.exit("linematch.c matches no pinned sha256")
t = src.decode()
names = ["line_len", "matching_chars", "matching_chars_iwhite", "count_n_matched_chars",
         "fastforward_buf_to_lnum"]
out = ["/* generated by build.py: verbatim from src/nvim/linematch.c @7b87ce8 */",
       "#define MATCH_CHAR_MAX_LEN 800",
       "static int matching_chars(const mmfile_t *m1, const mmfile_t *m2);"]
for n in names:
    m = re.search(r"^(static )?\w+ \*?" + n + r"\([^)]*\)\n\{.*?^\}\n", t, re.S | re.M)
    if not m: sys.exit("not found: " + n)
    out.append(m.group(0))
open(sys.argv[2], "w").write("\n".join(out))
