"""Writes lemmas_probe.smt2: probe_lemma of map_int.c, one check per n = 2^k (k = 0..31).
64-bit vectors hold every value exactly (T(s) < 2^63), so each unsat is an integer fact."""
h = lambda v: "#x%016x" % v
out = [";; probe_lemma; every check must be unsat. Generated by gen_probe_smt.py"]
for k in range(32):
    n, m = h(1 << k), h((1 << k) - 1)
    T = lambda s: f"(bvudiv (bvmul {s} (bvadd {s} {h(1)})) {h(2)})"
    # exactly the contract of probe_lemma: p is the old step, s = p + 1
    pre = (f"(declare-const i0 (_ BitVec 64))(declare-const p (_ BitVec 64))(declare-const last (_ BitVec 64))"
           f"(define-fun s () (_ BitVec 64) (bvadd p {h(1)}))"
           f"(assert (bvult i0 {n}))(assert (bvult last {n}))"
           f"(assert (bvule p (bvsub (bvmul {h(2)} {n}) {h(2)})))"
           f"(assert (= i0 (bvand (bvadd last {T('p')}) {m})))")
    w = h(2**32 - 1)  # x % 2^32 on values below 2^64
    # (p + 1) % 2^32 == p + 1 under the preconditions, then the step itself
    out.append(f"(push){pre}(assert (not (= (bvand s {w}) s)))(check-sat)(pop)")
    out.append(f"(push){pre}(assert (not (= (bvand (bvand (bvadd i0 s) {w}) {m}) "
               f"(bvand (bvadd last {T('s')}) {m}))))(check-sat)(pop)")
    out.append(f"(push){pre}(assert (= s (bvsub (bvmul {h(2)} {n}) {h(1)})))"
               f"(assert (not (= (bvand (bvadd last {T('s')}) {m}) last)))(check-sat)(pop)")
open(__file__.rsplit("/", 1)[0] + "/lemmas_probe.smt2", "w").write("\n".join(out) + "\n")
