"""Bit-operation lemmas for the charset.c proofs, written once and used two ways.

WP states them over mathematical integers, where SMT solvers treat & and << as
uninterpreted. `python3 -I lemmas.py` proves each one with Z3 bit-vectors (64-bit;
all values are non-negative and far below 2^63, so the bit-vector and integer
meanings agree). `--acsl` prints them as ACSL. The same strings feed both.
"""
import sys

# (name, variable, bounds, lhs, rhs)
LEMMAS = [
    ("mask15", "x", (0, 2 ** 32 - 1), "(x & 15)", "(x % 16)"),   # nr2hex: n & 0xf
    ("shl4", "x", (0, 15), "(x << 4)", "(x * 16)"),              # hexhex2nr: hex2nr(p[0]) << 4
    ("mask_lo", "x", (0, 255), "(x & 4294967055)", "(x & 15)"),   # vim_str2nr: the forced switch
]
# two variables, both in the same bounds: vim_str2nr's tool patch (tool_patches.flatten_str2nr)
# combines 0/1 truth values with & and |.
LEMMAS2 = [
    ("land01", ("a", "b"), (0, 1), "(a & b)", "(a * b)"),
    ("lor01", ("a", "b"), (0, 1), "(a | b)", "(a + b - a * b)"),
]


def acsl():
    out = ["/*@ // Generated by lemmas.py; each lemma is checked there with Z3 bit-vectors."]
    for name, v, (lo, hi), lhs, rhs in LEMMAS:
        out.append(f"    lemma {name}: \\forall integer {v}; {lo} <= {v} <= {hi} ==> {lhs} == {rhs};")
    for name, (v, w), (lo, hi), lhs, rhs in LEMMAS2:
        out.append(f"    lemma {name}: \\forall integer {v}, {w}; {lo} <= {v} <= {hi} && {lo} <= {w} <= {hi} ==> {lhs} == {rhs};")
    out.append("*/")
    return "\n".join(out)


def check():
    from z3 import BitVec, BitVecVal, And, Implies, Not, Solver, ULE, unsat
    ok = True
    for name, v, (lo, hi), lhs, rhs in LEMMAS:
        x = BitVec(v, 64)
        # z3 BitVec: % is signed remainder; with x >= 0 it equals the integer remainder
        f = Implies(And(ULE(BitVecVal(lo, 64), x), ULE(x, BitVecVal(hi, 64))),
                    eval(lhs, {}, {v: x}) == eval(rhs, {}, {v: x}))
        s = Solver(); s.add(Not(f)); r = s.check()
        print(f"{name}: {'PROVED' if r == unsat else 'FAILED'}"); ok &= r == unsat
    for name, (v, w), (lo, hi), lhs, rhs in LEMMAS2:
        a, b = BitVec(v, 64), BitVec(w, 64)
        rng = lambda t: And(ULE(BitVecVal(lo, 64), t), ULE(t, BitVecVal(hi, 64)))
        f = Implies(And(rng(a), rng(b)), eval(lhs, {}, {v: a, w: b}) == eval(rhs, {}, {v: a, w: b}))
        s = Solver(); s.add(Not(f)); r = s.check()
        print(f"{name}: {'PROVED' if r == unsat else 'FAILED'}"); ok &= r == unsat
    return ok


if __name__ == "__main__":
    if "--acsl" in sys.argv:
        print(acsl())
    else:
        sys.exit(0 if check() else 1)
