#!/usr/bin/env python3
"""Extract the menu.c name helpers verbatim from a Neovim checkout (sha256 pinned per function).
Usage: python3 -I build.py <neovim checkout> <out.c>"""
import hashlib, re, sys
NAMES = ["menu_is_winbar", "menu_namecmp", "menu_is_popup", "menu_is_toolbar",
         "menu_is_menubar", "menu_is_separator", "menu_is_hidden", "menu_skip_part"]
PINS = {}  # filled from pins.txt
src = open(sys.argv[1] + "/src/nvim/menu.c").read()
for line in open(__file__.rsplit("/", 1)[0] + "/pins.txt"):
    n, h = line.split(); PINS[n] = h
out = ["/* generated by build.py: verbatim from src/nvim/menu.c */",
       "#include <stdbool.h>", "#include <string.h>", "#define NUL '\\0'", "#define TAB '\\t'",
       "#define Ctrl_V 22", "#define MNU_HIDDEN_CHAR ']'",
       "static inline bool ascii_iswhite(int c) { return c == ' ' || c == '\\t'; }",
       "#define FUNC_ATTR_PURE", "#define FUNC_ATTR_WARN_UNUSED_RESULT", "#define FUNC_ATTR_NONNULL_ALL",
       "bool menu_is_popup(const char *const name);", "bool menu_is_toolbar(const char *const name);",
       "static bool menu_is_winbar(const char *const name);"]
for n in NAMES:
    m = re.search(r"^(?:static )?(?:bool|char \*)\s*" + n + r"\(.*?\n\}\n", src, re.M | re.S)
    if not m: sys.exit("not found: " + n)
    body = m.group(0)
    h = hashlib.sha256(body.encode()).hexdigest()
    if len(sys.argv) > 3 and sys.argv[3] == "--print-pins": print(n, h); continue
    if PINS.get(n) != h: sys.exit(f"sha256 mismatch for {n}: {h}")
    out.append(body)
if not (len(sys.argv) > 3): open(sys.argv[2], "w").write("\n".join(out) + "\n")
